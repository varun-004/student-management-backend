package com.example.student_management_system.ai.dto;

import lombok.AllArgsConstructor;
import lombok.Builder;
import lombok.Data;
import lombok.NoArgsConstructor;
import java.util.Map;
import java.util.List;

@Data
@Builder
@NoArgsConstructor
@AllArgsConstructor
public class AIPredictionResponse {
    
    private Long studentId;
    private String riskCategory;
    private Double riskProbability;
    private Double predictedPerformance;
    private Map<String, Double> classProbabilities;
    private Map<String, Double> featureImportance;
    private String modelVersion;
    
    // Aggregated contextual insights generated by Spring Boot
    private List<String> strengths;
    private List<String> weaknesses;
    private List<String> recommendations;
    private List<String> actionPlan;
    private String keyFactorSummary;
}
